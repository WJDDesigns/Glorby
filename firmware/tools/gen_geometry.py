#!/usr/bin/env python3
"""Writes usermods/glorby_fx/glorby_geo.h from the web app's lamp-map.json.

Usage: gen_geometry.py path/to/lamp-map.json > usermods/glorby_fx/glorby_geo.h
"""
import json, math, sys

m = json.load(open(sys.argv[1]))
V, F, cells = m["vertices"], m["faces"], m["cells"]
parent = m.get("parent") or [i // 4 for i in range(len(F))]

def unit(v):
    n = math.sqrt(sum(c * c for c in v)) or 1e-9
    return [c / n for c in v]

pos = [unit([sum(V[v][a] for v in f) / 3 for a in range(3)]) for f in F]
nbr = []
for i, f in enumerate(F):
    s = set(f)
    nbr.append([j for j, g in enumerate(F) if j != i and len(s & set(g)) == 2])
assert all(len(n) == 3 for n in nbr), "every triangle should have 3 neighbours"

def arr(rows, fmt):
    return ",\n  ".join("{" + ", ".join(fmt % x for x in r) + "}" if isinstance(r, (list, tuple)) else fmt % r for r in rows)

out = ["// Generated by firmware/tools/gen_geometry.py from web/lamp-map.json. Do not edit.",
       "#pragma once", "#include <stdint.h>", "",
       f"#define GLORBY_LEDS {len(F)}", "",
       "// Unit direction of each triangle's centre.",
       f"static const float GEO_POS[{len(F)}][3] = {{\n  {arr(pos, '%.6ff')}\n}};", "",
       "// Matrix cell (row-major on the 20x6 grid) that drives each triangle.",
       f"static const uint8_t GEO_CELL[{len(F)}] = {{{', '.join(map(str, cells))}}};", "",
       "// Which of the 20 icosahedron faces each triangle belongs to.",
       f"static const uint8_t GEO_PARENT[{len(F)}] = {{{', '.join(map(str, parent))}}};", "",
       "// The three triangles sharing an edge with each triangle.",
       f"static const uint8_t GEO_NEIGHBORS[{len(F)}][3] = {{\n  {arr(nbr, '%d')}\n}};", "",
       "// The 12 five-way corners of the icosahedron.",
       f"static const float GEO_MAIN[12][3] = {{\n  {arr([unit(v) for v in V[:12]], '%.6ff')}\n}};", ""]
n = m.get("noise")
if n:
    out += ["// Gradient noise tables, shared with the web and Home Assistant engines.",
            f"static const uint8_t NOISE_PERM[256] = {{{', '.join(map(str, n['perm']))}}};",
            f"static const float NOISE_GRAD[256][3] = {{\n  {arr(n['grad'], '%.6ff')}\n}};", ""]
print("\n".join(out))
